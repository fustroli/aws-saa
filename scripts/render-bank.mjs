// Renders src/data/bank/*.json into docs/question-bank/<domain>.md plus an index.
// The JSON is the source of truth; never edit the generated Markdown by hand.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const BANK = join(ROOT, 'src/data/bank')
const OUT = join(ROOT, 'docs/question-bank')

const DOMAINS = [
  { id: 'secure', name: 'Design Secure Architectures' },
  { id: 'resilient', name: 'Design Resilient Architectures' },
  { id: 'performant', name: 'Design High-Performing Architectures' },
  { id: 'cost', name: 'Design Cost-Optimized Architectures' },
]

const files = readdirSync(BANK)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => ({ file: f, task: f.match(/-(\d\.\d)\.json$/)[1], questions: JSON.parse(readFileSync(join(BANK, f), 'utf8')) }))

const letter = (id) => id.toUpperCase()

function renderQuestion(q) {
  const lines = [`### ${q.id}`, '', `_${q.services.join(', ')}_`, '', q.text, '']
  for (const o of q.options) lines.push(`- **${letter(o.id)}.** ${o.text}`)
  lines.push('', '<details><summary>Answer</summary>', '')
  lines.push(`**Correct: ${q.correct.map(letter).join(', ')}**`, '')
  for (const o of q.options) lines.push(`- **${letter(o.id)}** ${q.correct.includes(o.id) ? '✅' : '❌'} ${o.note}`)
  lines.push('', q.explanation, '', '</details>', '')
  return lines.join('\n')
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const index = ['# SAA-C03 question bank', '', 'Generated by `npm run bank:md` from `src/data/bank/*.json`. Do not edit by hand.', '']
let total = 0
for (const d of DOMAINS) {
  const domainFiles = files.filter((f) => f.file.startsWith(`${d.id}-`))
  const count = domainFiles.reduce((n, f) => n + f.questions.length, 0)
  total += count
  index.push(`- [${d.name}](${d.id}.md): ${count} (${domainFiles.map((f) => `${f.task}: ${f.questions.length}`).join(', ') || 'none'})`)

  const body = [`# ${d.name}`, '', `${count} questions.`, '']
  for (const f of domainFiles) {
    body.push(`## Task ${f.task}`, '')
    for (const q of f.questions) body.push(renderQuestion(q))
  }
  writeFileSync(join(OUT, `${d.id}.md`), body.join('\n'))
}
index.push('', `**Total: ${total}**`, '')
writeFileSync(join(OUT, 'README.md'), index.join('\n'))
console.log(`Rendered ${total} questions to docs/question-bank/`)
